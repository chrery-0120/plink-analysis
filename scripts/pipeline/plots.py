def _manhattan_core(
    data: Any,
    out_path: Path,
    *,
    chr_col: str,
    bp_col: str,
    val_col: str,
    logp: bool,
    title: str,
    ylabel: str,
    threshold: float | None = None,
    threshold_label: str | None = None,
    secondary: float | None = None,
    secondary_label: str | None = None,
    highlight: bool = True,
    label_top: bool = True,
    **kwargs,
) -> Path:
    if not isinstance(data, pd.DataFrame):
        data = _frame(data)
    if data.empty:
        return _placeholder(out_path, title, "input table is empty")
    d = data.copy()
    d[chr_col] = d[chr_col].astype(str).str.strip()
    d[bp_col] = pd.to_numeric(d[bp_col], errors="coerce")
    values = pd.to_numeric(d[val_col], errors="coerce")
    if logp:
        values = values.where(values > 0)
        score = -np.log10(values.clip(lower=1e-300))
    else:
        score = values
    d = d.assign(_val=values.to_numpy(dtype=float), _score=np.asarray(score, dtype=float))
    d = d.replace([np.inf, -np.inf], np.nan).dropna(subset=[bp_col, "_score"])
    if d.empty:
        reason = "no valid CHR/BP/{} rows".format(val_col)
        if logp:
            reason += " (p-values must be > 0)"
        return _placeholder(out_path, title, reason)

    order = sorted(d[chr_col].unique().tolist(), key=_chrom_sort_key)
    d["_bp0"] = d[bp_col].clip(lower=0)
    spans = {c: max(float(d.loc[d[chr_col] == c, "_bp0"].max()), 1.0) for c in order}
    total = sum(spans.values())
    gap = max(total * 0.01, 1.0)
    offsets: dict[str, float] = {}
    cursor = 0.0
    for chrom in order:
        offsets[chrom] = cursor
        cursor += spans[chrom] + gap
    d["_pos"] = d[chr_col].map(offsets) + d["_bp0"]

    fig, ax = plt.subplots(figsize=_FIGSIZE_WIDE)
    point_size = float(kwargs.get("point_size", 8))
    for i, chrom in enumerate(order):
        sub = d[d[chr_col] == chrom]
        ax.scatter(
            sub["_pos"],
            sub["_score"],
            s=point_size,
            color=_MANHATTAN_COLORS[i % 2],
            alpha=0.85,
            linewidths=0,
            rasterized=len(d) > 30000,
        )

    ymax = float(d["_score"].max())
    line_y = None
    if threshold is not None:
        try:
            t = float(threshold)
        except Exception:
            t = None
        if t is not None and math.isfinite(t) and t > 0:
            line_y = -math.log10(t) if logp else t
            if line_y > 0:
                ax.axhline(
                    line_y,
                    color=_C_RED,
                    lw=1.3,
                    ls="--",
                    label=threshold_label or f"threshold = {t:g}",
                    zorder=2,
                )
                if highlight:
                    sig = d[d["_val"] <= t] if logp else d[d["_score"] >= t]
                    if len(sig):
                        ax.scatter(
                            sig["_pos"],
                            sig["_score"],
                            s=point_size * 2.0,
                            color=_C_RED,
                            alpha=0.9,
                            linewidths=0,
                            zorder=3,
                            label=f"significant (n={len(sig):,})",
                        )
    if secondary is not None:
        try:
            s = float(secondary)
        except Exception:
            s = None
        if s is not None and math.isfinite(s) and s > 0:
            y2 = -math.log10(s) if logp else s
            ax.axhline(y2, color=_C_ORANGE, lw=1.0, ls=":", label=secondary_label or f"secondary = {s:g}")

    if label_top and logp:
        label_col = _pick(d, "SNP", "ID", "rsid", "variant", "MARKER")
        if label_col is not None:
            top = d.nlargest(min(3, len(d)), "_score")
            for _, row in top.iterrows():
                ax.annotate(
                    str(row[label_col]),
                    xy=(row["_pos"], row["_score"]),
                    xytext=(0, 7),
                    textcoords="offset points",
                    ha="center",
                    fontsize=7,
                    color="#333333",
                    bbox=dict(boxstyle="round,pad=0.15", fc="white", ec="#d0d4da", lw=0.5, alpha=0.85),
                )

    midpoints = [offsets[c] + spans[c] / 2.0 for c in order]
    ax.set_xticks(midpoints)
    rotation = 90 if len(order) > 14 else (45 if len(order) > 8 else 0)
    ax.set_xticklabels(order, rotation=rotation, fontsize=7.5 if len(order) > 14 else 9)
    ax.set_xlim(-gap * 0.5, cursor - gap)
    top_limit = max(ymax, line_y or 0.0)
    ax.set_ylim(0, top_limit * 1.15 + 0.05)
    ax.set_xlabel("Chromosome")
    ax.set_ylabel(ylabel)
    ax.set_title(title)
    ax.xaxis.grid(False)
    handles, labels = ax.get_legend_handles_labels()
    if handles:
        ax.legend(loc="upper right", frameon=True, fontsize=8, ncol=min(2, len(handles)))
    _axis_stats(ax, f"N = {len(d):,}\nchromosomes = {len(order)}", loc="upper left")
    return _savefig(fig, out_path)


def plot_manhattan(df: Any, out_path: Path, *, bonferroni: float | None = None, **kwargs) -> Path:
    """Genome-wide Manhattan plot of -log10(P) with optional Bonferroni line."""
    title = kwargs.get("title", "Manhattan plot")
    frame = _frame(df)
    chr_col = _pick(frame, "CHR", "chr", "Chromosome", "chrom")
    bp_col = _pick(frame, "BP", "bp", "POS", "pos", "position")
    p_col = _pick(frame, "P", "p", "Pval", "PVAL", "p_value")
    if chr_col is None or bp_col is None or p_col is None:
        missing = [n for n, c in (("CHR", chr_col), ("BP", bp_col), ("P", p_col)) if c is None]
        return _placeholder(
            out_path,
            title,
            "required columns {} not found (expected: CHR, BP, P)".format("/".join(missing)),
        )
    suggestive = kwargs.get("suggestive")
    return _manhattan_core(
        frame,
        out_path,
        chr_col=chr_col,
        bp_col=bp_col,
        val_col=p_col,
        logp=True,
        title=title,
        ylabel=kwargs.get("ylabel", "-log10(P)"),
        threshold=bonferroni,
        threshold_label=(
            f"Bonferroni = {bonferroni:.3g}" if bonferroni is not None and math.isfinite(float(bonferroni)) else None
        ),
        secondary=suggestive,
        secondary_label=(
            f"suggestive = {suggestive:.3g}" if suggestive is not None and math.isfinite(float(suggestive)) else None
        ),
        highlight=True,
        point_size=kwargs.get("point_size", 8),
    )


