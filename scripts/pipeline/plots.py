def plot_maf_spectrum(maf: Any, out_path: Path, **kwargs) -> Path:
    """Histogram of minor allele frequencies (QC)."""
    title = kwargs.get("title", "Minor allele frequency spectrum")
    values = _numeric(maf)
    if values.size == 0:
        return _placeholder(out_path, title, "no finite MAF values in the input")
    threshold = float(kwargs.get("maf_threshold", 0.01))
    values = np.clip(values, 0.0, 0.5)
    fig, ax = plt.subplots(figsize=_FIGSIZE)
    ax.hist(values, bins=np.linspace(0, 0.5, 51), color=_C_BLUE, edgecolor="white", linewidth=0.4)
    mean = float(np.mean(values))
    ax.axvline(mean, color=_C_ORANGE, lw=1.4, ls="--", label=f"mean = {_fmt_num(mean)}")
    ax.axvline(threshold, color=_C_RED, lw=1.2, ls=":", label=f"threshold = {threshold:g}")
    frac_below = float(np.mean(values < threshold))
    ax.set_xlabel("Minor allele frequency (MAF)")
    ax.set_ylabel("Number of variants")
    ax.set_title(title)
    ax.set_xlim(0.0, 0.5)
    ax.legend(loc="upper right", frameon=True)
    _axis_stats(ax, f"N = {values.size:,}\nMAF < {threshold:g}: {frac_below:.2%}")
    return _savefig(fig, out_path)


def plot_missingness(sample_miss: Any, variant_miss: Any, out_path: Path, **kwargs) -> Path:
    """Per-sample and per-variant genotype missingness distributions."""
    title = kwargs.get("title", "Genotype missingness")
    samples = _numeric(sample_miss)
    variants = _numeric(variant_miss)
    if samples.size == 0 and variants.size == 0:
        return _placeholder(out_path, title, "no finite missingness values in the input")
    mind = float(kwargs.get("mind", 0.10))
    geno = float(kwargs.get("geno", 0.10))
    fig, axes = plt.subplots(1, 2, figsize=(11.0, 4.2))
    panels = (
        (axes[0], samples, "Per-sample missingness", f"mind = {mind:.0%}", mind, _C_BLUE),
        (axes[1], variants, "Per-variant missingness", f"geno = {geno:.0%}", geno, _C_ORANGE),
    )
    for ax, arr, panel_title, thr_label, thr, colour in panels:
        if arr.size == 0:
            ax.text(0.5, 0.5, "No data", ha="center", va="center", transform=ax.transAxes, color=_C_GRAY)
            ax.set_title(panel_title)
            continue
        scale = 100.0 if float(np.nanmax(arr)) <= 1.0 else 1.0
        pct = arr * scale
        bins = np.linspace(0, max(1.0, float(np.nanmax(pct)) * 1.05), 50)
        ax.hist(pct, bins=bins, color=colour, edgecolor="white", linewidth=0.4)
        ax.axvline(thr * 100.0, color=_C_RED, lw=1.3, ls="--", label=thr_label)
        ax.set_xlabel("Missing genotype rate (%)")
        ax.set_ylabel("Count")
        ax.set_title(panel_title)
        ax.legend(loc="upper right", frameon=True)
        _axis_stats(ax, f"N = {arr.size:,}\nmean = {float(np.mean(pct)):.3f}%")
    fig.suptitle(title, fontsize=13, fontweight="bold", y=1.02)
    return _savefig(fig, out_path)


def plot_het_distribution(het: Any, out_path: Path, **kwargs) -> Path:
    """Distribution of the PLINK ``--het`` inbreeding coefficient *F*."""
    title = kwargs.get("title", "Heterozygosity-based inbreeding coefficient (F)")
    df = _frame(het)
    f_col = _pick(df, "F", "f", "Fhat", "F_HAT")
    if f_col is None:
        return _placeholder(out_path, title, "required column F not found (expected columns: F, IID)")
    values = _numeric(df[f_col])
    if values.size == 0:
        return _placeholder(out_path, title, "column F contains no finite values")
    sd_mult = float(kwargs.get("het_sd", 3.0))
    mean = float(np.mean(values))
    sd = float(np.std(values, ddof=1)) if values.size > 1 else 0.0
    fig, ax = plt.subplots(figsize=_FIGSIZE)
    ax.hist(values, bins=50, color=_C_BLUE, edgecolor="white", linewidth=0.4, density=False)
    ax.axvline(mean, color=_C_ORANGE, lw=1.4, ls="--", label=f"mean = {_fmt_num(mean)}")
    if sd > 0:
        ax.axvline(mean - sd_mult * sd, color=_C_RED, lw=1.1, ls=":", label=f"mean ± {sd_mult:g} SD")
        ax.axvline(mean + sd_mult * sd, color=_C_RED, lw=1.1, ls=":")
    ax.set_xlabel("Inbreeding coefficient F")
    ax.set_ylabel("Number of samples")
    ax.set_title(title)
    ax.legend(loc="upper right", frameon=True)
    _axis_stats(ax, f"N = {values.size:,}\nSD = {_fmt_num(sd)}", loc="upper left")
    return _savefig(fig, out_path)


def _qq_plot(
    pvals: Any,
    out_path: Path,
    *,
    title: str,
    lambda_label: str = "lambda",
    lambda_gc: float | None = None,
    note: str | None = None,
    **kwargs,
) -> Path:
    p = _clean_p(pvals)
    if p.size < 2:
        return _placeholder(out_path, title, "fewer than two valid p-values in the input")
    p_sorted = np.sort(p)
    n = p_sorted.size
    expected = -np.log10((np.arange(1, n + 1) - 0.5) / n)
    observed = -np.log10(np.clip(p_sorted, 1e-300, 1.0))

    fig, ax = plt.subplots(figsize=(6.4, 6.0))
    # 95% point-wise envelope of the order statistics (Beta(i, n-i+1)).
    if _scipy_stats is not None:
        try:
            ranks = np.arange(1, n + 1)
            lower = _scipy_stats.beta.ppf(0.025, ranks, n - ranks + 1)
            upper = _scipy_stats.beta.ppf(0.975, ranks, n - ranks + 1)
            lower = np.clip(lower, 1e-300, 1.0)
            upper = np.clip(upper, 1e-300, 1.0)
            ax.fill_between(
                expected,
                -np.log10(upper),
                -np.log10(lower),
                color="#cfd8e3",
                alpha=0.45,
                linewidth=0,
                label="95% envelope",
                zorder=1,
            )
        except Exception:  # pragma: no cover
            pass
    limit = max(float(expected.max()), float(observed.max()), 1.0) * 1.05
    ax.plot([0, limit], [0, limit], color=_C_GRAY, lw=1.1, ls="--", label="null (y = x)", zorder=2)
    ax.scatter(expected, observed, s=14, color=_C_BLUE, alpha=0.85, linewidths=0, zorder=3, label="observed")
    ax.set_xlim(0, limit)
    ax.set_ylim(0, limit)
    ax.set_aspect("equal", adjustable="box")
    ax.set_xlabel("Expected -log10(p)")
    ax.set_ylabel("Observed -log10(p)")
    ax.set_title(title)
    ax.legend(loc="upper left", frameon=True)

    lam = lambda_gc
    if lam is None:
        lam = _lambda_gc(p)
    lines = []
    if lam is not None and math.isfinite(float(lam)):
        lines.append(f"{lambda_label} = {float(lam):.3f}")
    lines.append(f"N = {n:,}")
    if note:
        lines.append(note)
    _axis_stats(ax, "\n".join(lines), loc="lower right")
    return _savefig(fig, out_path)


def plot_hwe_qq(pvals: Any, out_path: Path, **kwargs) -> Path:
    """QQ plot of Hardy-Weinberg equilibrium p-values (QC diagnostics)."""
    title = kwargs.get("title", "QQ plot of HWE p-values")
    p = _clean_p(pvals)
    if p.size < 2:
        return _placeholder(out_path, title, "fewer than two valid HWE p-values in the input")
    fraction = float(np.mean(p < float(kwargs.get("extreme_p", 1e-6))))
    lam = _lambda_gc(p)
    note = f"p < {kwargs.get('extreme_p', 1e-6):g}: {fraction:.2%}"
    return _qq_plot(p, out_path, title=title, lambda_label="lambda (HWE)", lambda_gc=lam, note=note)


def plot_phenotype_distribution(pheno: Any, out_path: Path, *, kind: str = "quantitative", **kwargs) -> Path:
    """Histogram (quantitative) or bar chart (binary) of the analysed phenotype."""
    kind_norm = str(kind).strip().lower()
    title = kwargs.get("title", "Phenotype distribution")
    raw = _to_series(pheno)
    if isinstance(raw, pd.Series) and raw.dropna().empty:
        return _placeholder(out_path, title, "phenotype vector is empty")
    is_binary = kind_norm in {"binary", "case_control", "casecontrol", "binary_trait", "categorical"}
    if is_binary:
        cleaned = raw.dropna()
        if cleaned.empty:
            return _placeholder(out_path, title, "phenotype vector is empty")
        counts = cleaned.astype(str).value_counts().sort_index()
        fig, ax = plt.subplots(figsize=_FIGSIZE)
        bars = ax.bar([str(i) for i in counts.index], [int(v) for v in counts.values], color=_C_BLUE, width=0.6)
        total = int(counts.sum())
        for bar, value in zip(bars, counts.values):
            ax.text(
                bar.get_x() + bar.get_width() / 2,
                bar.get_height(),
                f"{int(value):,}\n{value / max(total, 1):.1%}",
                ha="center",
                va="bottom",
                fontsize=9,
            )
        ax.set_xlabel("Phenotype class")
        ax.set_ylabel("Number of samples")
        ax.set_title(title)
        ax.set_ylim(0, max(int(counts.max()) * 1.18, 1))
        _axis_stats(ax, f"N = {total:,}")
        return _savefig(fig, out_path)

    values = _numeric(raw)
    if values.size == 0:
        return _placeholder(out_path, title, "phenotype contains no finite numeric values (is it a binary trait?)")
    fig, ax = plt.subplots(figsize=_FIGSIZE)
    ax.hist(values, bins=40, color=_C_BLUE, edgecolor="white", linewidth=0.4, density=True)
    mean = float(np.mean(values))
    sd = float(np.std(values, ddof=1)) if values.size > 1 else 0.0
    ax.axvline(mean, color=_C_ORANGE, lw=1.4, ls="--", label=f"mean = {_fmt_num(mean)}")
    ax.set_xlabel("Phenotype value")
    ax.set_ylabel("Density")
    ax.set_title(title)
    ax.legend(loc="upper right", frameon=True)
    _axis_stats(ax, f"N = {values.size:,}\nSD = {_fmt_num(sd)}", loc="upper left")
    return _savefig(fig, out_path)


