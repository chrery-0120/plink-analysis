def plot_ld_decay(bins: Any, out_path: Path, **kwargs) -> Path:
    """LD decay curve: mean r^2 as a function of physical distance."""
    title = kwargs.get("title", "LD decay")
    df = _frame(bins)
    dist_col = _pick(df, "distance_bp", "DISTANCE_BP", "distance", "dist_bp", "bp")
    r2_col = _pick(df, "mean_r2", "MEAN_R2", "r2", "R2", "mean_r")
    if dist_col is None or r2_col is None:
        return _placeholder(
            out_path,
            title,
            "required columns distance_bp/mean_r2 not found (expected: distance_bp, mean_r2)",
        )
    dist = pd.to_numeric(df[dist_col], errors="coerce").to_numpy(dtype=float)
    r2 = pd.to_numeric(df[r2_col], errors="coerce").to_numpy(dtype=float)
    keep = np.isfinite(dist) & np.isfinite(r2)
    dist, r2 = dist[keep], r2[keep]
    if dist.size == 0:
        return _placeholder(out_path, title, "LD bins contain no finite values")
    order = np.argsort(dist)
    dist, r2 = dist[order], r2[order]
    # deduplicate identical distances for a clean line plot
    unique_dist, unique_idx = np.unique(dist, return_index=True)
    if unique_dist.size > 1:
        dist, r2 = dist[unique_idx], r2[unique_idx]
    x_kb = dist / 1000.0
    fig, ax = plt.subplots(figsize=_FIGSIZE)
    ax.plot(x_kb, r2, color=_C_BLUE, marker="o", markersize=4.5, lw=1.4, label="mean r²")
    threshold = float(kwargs.get("r2_threshold", 0.2))
    ax.axhline(threshold, color=_C_ORANGE, lw=1.1, ls="--", label=f"r² = {threshold:g}")
    half = float(r2[0] / 2.0) if r2.size else 0.0
    if half > 0:
        ax.axhline(half, color=_C_GRAY, lw=0.9, ls=":", label=f"half of r²(0) = {half:.2f}")
    ax.set_xlabel("Physical distance (kb)")
    ax.set_ylabel("Mean r²")
    ax.set_title(title)
    ax.set_ylim(0, max(float(np.nanmax(r2)) * 1.15, 0.1))
    ax.legend(loc="upper right", frameon=True)
    _axis_stats(ax, f"bins = {dist.size:,}\nmax distance = {x_kb.max():,.0f} kb", loc="upper left")
    return _savefig(fig, out_path)


