def pca_variance_percent(eigvals: Any, *, n_samples: Any = None, n_rows: Any = None) -> np.ndarray:
    """Per-PC variance explained as a percentage of the *whole sample set*.

    PLINK 1.9 ``--pca`` eigenvalues come from the variance-standardised genetic
    relationship matrix, whose trace equals the number of samples ``N``.  The
    percentage of total variance explained by PC *i* is therefore
    ``eigenvalue_i / N * 100`` -- **not** ``eigenvalue_i / sum(first k
    eigenvalues)``.  The latter (a common mistake) inflates PC1 by roughly
    ``N / k``.

    Parameters
    ----------
    eigvals : array-like
        Eigenvalues, typically read from ``*.eigenval``.
    n_samples : int, optional
        Number of samples analysed by ``--pca`` (the correct denominator).
    n_rows : int, optional
        Fallback denominator when ``n_samples`` is not given, e.g. the number of
        rows in an eigenvector table (one row per sample).

    Returns
    -------
    numpy.ndarray
        ``eigenvalue_i / N * 100`` for every finite input eigenvalue.  Returns an
        empty array when no positive denominator is available (callers should
        then fall back to the "relative to retained PCs" display).
    """
    ev = _numeric(eigvals)
    denominator = 0
    for candidate in (n_samples, n_rows):
        try:
            value = int(candidate) if candidate is not None else 0
        except Exception:
            value = 0
        if value > 0:
            denominator = value
            break
    if denominator <= 0 or ev.size == 0:
        return np.asarray([], dtype=float)
    return ev / float(denominator) * 100.0


def plot_pca_scatter(eigenvec: Any, eigvals: Any, out_path: Path, groups: Any = None, **kwargs) -> Path:
    """PC1 vs PC2 scatter; optionally coloured by a group/breed annotation.

    Variance percentages on the axes use ``n_samples`` when supplied; otherwise
    the number of rows of *eigenvec* (one sample per row) is used as the
    denominator (the correct PLINK 1.9 convention, see
    :func:`pca_variance_percent`).
    """
    title = kwargs.get("title", "PCA scatter (PC1 vs PC2)")
    df = _frame(eigenvec)
    if df.empty:
        return _placeholder(out_path, title, "eigenvector table is empty")
    pc1 = _pick(df, "PC1", "pc1", "PC_1")
    pc2 = _pick(df, "PC2", "pc2", "PC_2")
    if pc1 is None or pc2 is None:
        numeric_cols = [
            c
            for c in df.columns
            if pd.api.types.is_numeric_dtype(df[c]) and str(c).strip().upper() not in {"FID"}
        ]
        if len(numeric_cols) < 2:
            return _placeholder(
                out_path,
                title,
                "columns PC1/PC2 not found and fewer than two numeric columns are available",
            )
        pc1, pc2 = numeric_cols[0], numeric_cols[1]
    x = pd.to_numeric(df[pc1], errors="coerce")
    y = pd.to_numeric(df[pc2], errors="coerce")
    keep = np.isfinite(x.to_numpy(dtype=float)) & np.isfinite(y.to_numpy(dtype=float))
    if not keep.any():
        return _placeholder(out_path, title, "PC1/PC2 contain no finite values")
    df = df.loc[keep].reset_index(drop=True)
    x = x.loc[keep].reset_index(drop=True).to_numpy(dtype=float)
    y = y.loc[keep].reset_index(drop=True).to_numpy(dtype=float)

    # Variance explained from eigenvalues.  PLINK 1.9 eigenvalues sum to the
    # sample count N (trace of the variance-standardised GRM), so the correct
    # per-PC percentage is eigenvalue / N * 100.  Use n_samples when given,
    # otherwise one eigenvector row == one sample (the most reliable default).
    eigenvalue_pct: dict[int, float] = {}
    try:
        ev = _numeric(eigvals)
        ev = ev[ev > 0]
        n_used = kwargs.get("n_samples")
        try:
            if n_used is not None and int(n_used) <= 0:
                n_used = None
        except Exception:
            n_used = None
        if n_used is None:
            n_used = len(df)
        pct = pca_variance_percent(ev, n_samples=n_used)
        for i in range(min(pct.size, 2)):
            eigenvalue_pct[i] = float(pct[i])
    except Exception:  # pragma: no cover
        pass
    xlabel = f"PC1 ({eigenvalue_pct[0]:.1f}% variance)" if 0 in eigenvalue_pct else "PC1"
    ylabel = f"PC2 ({eigenvalue_pct[1]:.1f}% variance)" if 1 in eigenvalue_pct else "PC2"

    iid_col = _pick(df, "IID", "id", "sample", "IID_STR")
    ids = df[iid_col].astype(str).tolist() if iid_col is not None else [str(i) for i in df.index]
    group_series = _group_series(groups, ids)

    fig, ax = plt.subplots(figsize=(7.4, 5.8))
    if group_series is not None:
        labels = [("NA" if pd.isna(v) else str(v)) for v in group_series.to_numpy()]
        categories = sorted(set(labels), key=lambda v: (v == "NA", v))
        colors = _discrete_colors(len(categories))
        markers = ["o", "s", "^", "D", "v", "P", "X", "*", "h", "<", ">", "p"]
        for idx, category in enumerate(categories):
            mask = np.asarray([lab == category for lab in labels])
            ax.scatter(
                x[mask],
                y[mask],
                s=26,
                color=colors[idx],
                marker=markers[idx % len(markers)],
                alpha=0.85,
                linewidths=0.4,
                edgecolors="white",
                label=f"{category} (n={int(mask.sum())})",
            )
        ax.legend(
            loc="upper right",
            frameon=True,
            fontsize=8.5,
            title=kwargs.get("group_name", "Group"),
            ncol=1 if len(categories) <= 8 else 2,
        )
    else:
        ax.scatter(x, y, s=24, color=_C_BLUE, alpha=0.8, linewidths=0.4, edgecolors="white")
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    ax.set_title(title)
    ax.axhline(0, color="#b8bec7", lw=0.7, zorder=0)
    ax.axvline(0, color="#b8bec7", lw=0.7, zorder=0)
    _axis_stats(ax, f"N = {x.size:,}", loc="lower left")
    return _savefig(fig, out_path)


def plot_pca_scree(eigvals: Any, out_path: Path, **kwargs) -> Path:
    """Scree plot of eigenvalues with cumulative variance explained.

    Pass ``n_samples`` (the number of samples used by ``--pca``) to show
    *percentage of the whole sample set*: because PLINK 1.9 eigenvalues sum to
    about ``N``, ``PC_i % = eigenvalue_i / N * 100``.  This is the recommended
    mode (stage_popgen/stage_qc pass it explicitly).  The cumulative curve is
    simply the running sum of these percentages and may exceed 100 when only the
    first few eigenvalues are shown (or when negative eigenvalues exist); a note
    on the figure says so.

    Without ``n_samples`` the plot falls back to "relative to retained PCs":
    bars show raw eigenvalues (labelled "Eigenvalue (not %)") and the cumulative
    curve is the fraction of the *retained* eigenvalues only.  That mode is kept
    for backwards compatibility but must not be reported as "% of total
    variance".
    """
    title = kwargs.get("title", "PCA scree plot")
    all_ev = _numeric(eigvals)
    all_ev = all_ev[all_ev > 0]
    if all_ev.size == 0:
        return _placeholder(out_path, title, "no positive eigenvalues in the input")
    n_requested = 0
    try:
        n_requested = int(kwargs.get("n_samples") or 0)
    except Exception:
        n_requested = 0
    max_shown = int(kwargs.get("max_pcs", 50) or 50)
    truncated = all_ev.size > max_shown
    ev = all_ev[:max_shown]
    idx = np.arange(1, ev.size + 1)

    fig, ax = plt.subplots(figsize=_FIGSIZE)
    if n_requested > 0:
        pct = pca_variance_percent(ev, n_samples=n_requested)
        if pct.size == 0:  # pragma: no cover - defensive
            pct = ev / float(n_requested) * 100.0
        cumulative = np.cumsum(pct)
        ax.bar(idx, pct, color=_C_BLUE, width=0.7, label=f"Variance explained (% of N = {n_requested:,})")
        ax.set_ylabel("Variance explained (%)")
        ax2 = ax.twinx()
        ax2.plot(idx, cumulative, color=_C_ORANGE, marker="o", markersize=3.5, lw=1.4, label="Cumulative")
        ax2.set_ylabel("Cumulative variance explained (%)")
        top = max(105.0, float(cumulative.max()) * 1.08)
        ax2.set_ylim(0, top)
        ax2.grid(False)
        ax.set_title(f"{title} (N = {n_requested:,})")
        stats = (
            f"PC1 = {pct[0]:.2f}%\n"
            f"PC1-5 = {cumulative[min(4, ev.size - 1)]:.2f}%"
        )
        if truncated or float(cumulative.max()) > 100.0:
            ax.text(
                0.02,
                0.03,
                f"Note: only the first {ev.size} of all N PCs are shown; cumulative % "
                "is normalised by the full sample count N and may exceed 100 in extreme cases.",
                transform=ax.transAxes,
                fontsize=7.2,
                color=_C_GRAY,
                style="italic",
                va="bottom",
            )
    else:
        # Legacy / fallback mode: relative to retained PCs, NOT % of all N.
        cumulative = np.cumsum(ev) / ev.sum() * 100.0
        ax.bar(idx, ev, color=_C_BLUE, width=0.7, label="Eigenvalue")
        ax.set_ylabel("Eigenvalue (not %)")
        ax2 = ax.twinx()
        ax2.plot(idx, cumulative, color=_C_ORANGE, marker="o", markersize=3.5, lw=1.4,
                 label="Cumulative (relative to retained PCs)")
        ax2.set_ylabel("Cumulative fraction of retained PCs (%)")
        ax2.set_ylim(0, 105)
        ax2.grid(False)
        ax.set_title(f"{title} (relative to retained PCs)")
        stats = (
            f"PC1 eigenvalue = {ev[0]:.4f}\n"
            f"PC1-5 = {cumulative[min(4, ev.size - 1)]:.1f}% of retained PCs"
        )
        if truncated:
            ax.text(
                0.02,
                0.03,
                f"Note: only the first {ev.size} of {all_ev.size} retained PCs are shown; "
                "percentages are relative to shown PCs, not to all samples.",
                transform=ax.transAxes,
                fontsize=7.2,
                color=_C_GRAY,
                style="italic",
                va="bottom",
            )
    ax.set_xlabel("Principal component")
    ax.set_xticks(idx if ev.size <= 20 else np.linspace(1, ev.size, 10, dtype=int))
    handles1, labels1 = ax.get_legend_handles_labels()
    handles2, labels2 = ax2.get_legend_handles_labels()
    ax.legend(handles1 + handles2, labels1 + labels2, loc="center right", frameon=True, fontsize=8.5)
    _axis_stats(ax, stats)
    return _savefig(fig, out_path)


