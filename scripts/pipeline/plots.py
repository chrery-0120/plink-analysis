def plot_kinship_heatmap(mat: Any, ids: Any, out_path: Path, **kwargs) -> Path:
    """Heatmap of a sample-by-sample kinship / PI_HAT matrix."""
    title = kwargs.get("title", "Kinship matrix")
    labels: list[str] | None = None
    if isinstance(mat, pd.DataFrame):
        try:
            arr = mat.to_numpy(dtype=float)
        except Exception:
            return _placeholder(out_path, title, "kinship matrix contains non-numeric values")
        labels = [str(i) for i in mat.index]
        if ids is not None:
            try:
                labels = [str(i) for i in ids]
            except Exception:
                pass
    else:
        try:
            arr = np.asarray(mat, dtype=float)
        except Exception:
            return _placeholder(out_path, title, "kinship matrix cannot be converted to a numeric array")
        if ids is not None:
            try:
                labels = [str(i) for i in ids]
            except Exception:
                labels = None
    if arr.ndim != 2 or arr.size == 0:
        return _placeholder(out_path, title, "kinship matrix is empty or not two-dimensional")
    if arr.shape[0] != arr.shape[1]:
        return _placeholder(out_path, title, f"kinship matrix is not square (shape {arr.shape})")
    n = arr.shape[0]
    if n < 2:
        return _placeholder(out_path, title, "at least two samples are required for a heatmap")
    if labels is None or len(labels) != n:
        labels = [str(i) for i in range(n)]
    masked = np.ma.masked_invalid(arr)
    finite_vals = arr[np.isfinite(arr)]
    if finite_vals.size == 0:
        return _placeholder(out_path, title, "kinship matrix contains only NaN values")
    vmax = float(np.nanmax(np.abs(finite_vals))) or 1.0
    size = 7.2 if n < 60 else 8.6
    fig, ax = plt.subplots(figsize=(size, size * 0.88))
    cmap = "RdBu_r" if float(np.nanmin(finite_vals)) < 0 else "viridis"
    im = ax.imshow(masked, cmap=cmap, vmin=-vmax, vmax=vmax, interpolation="nearest", aspect="equal")
    cbar = fig.colorbar(im, ax=ax, fraction=0.046, pad=0.03)
    cbar.set_label("Kinship / PI_HAT")
    step = max(1, n // 20)
    ticks = list(range(0, n, step))
    ax.set_xticks(ticks)
    ax.set_yticks(ticks)
    ax.set_xticklabels([labels[i] for i in ticks], rotation=90, fontsize=6.5)
    ax.set_yticklabels([labels[i] for i in ticks], fontsize=6.5)
    ax.set_title(title)
    ax.grid(False)
    _axis_stats(ax, f"N = {n:,}", loc="lower left")
    return _savefig(fig, out_path)


