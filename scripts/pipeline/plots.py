def _savefig(fig: "plt.Figure", out_path: Path | str) -> Path:
    """Save *fig* to *out_path* and close it; guarantees a non-empty PNG."""
    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    try:
        fig.tight_layout()
    except Exception:  # pragma: no cover - tight_layout is best effort
        pass
    fig.savefig(out, dpi=DPI, bbox_inches="tight", facecolor="white", pad_inches=0.18)
    plt.close(fig)
    return out


def _placeholder(out_path: Path | str, title: str, reason: str) -> Path:
    """Write a placeholder figure explaining why the real plot is missing."""
    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=_FIGSIZE)
    ax.axis("off")
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.text(
        0.5,
        0.66,
        title,
        ha="center",
        va="center",
        fontsize=14,
        fontweight="bold",
        color="#333333",
        transform=ax.transAxes,
    )
    ax.text(
        0.5,
        0.48,
        "Figure not available",
        ha="center",
        va="center",
        fontsize=11,
        color="#8a8f98",
        transform=ax.transAxes,
    )
    ax.text(
        0.5,
        0.30,
        textwrap.fill(str(reason), 88),
        ha="center",
        va="center",
        fontsize=8.8,
        color="#5f6368",
        transform=ax.transAxes,
    )
    ax.text(
        0.5,
        0.08,
        "placeholder generated by plink-analysis",
        ha="center",
        va="center",
        fontsize=7,
        color="#b0b4ba",
        transform=ax.transAxes,
    )
    return _savefig(fig, out)


def _to_series(data: Any, name: str = "value") -> pd.Series:
    """Best-effort conversion of arbitrary input to a 1-D pandas Series."""
    if isinstance(data, pd.Series):
        return data
    if isinstance(data, pd.DataFrame):
        if data.shape[1] == 0:
            return pd.Series(dtype=float, name=name)
        return data.iloc[:, 0]
    if data is None:
        return pd.Series(dtype=float, name=name)
    if isinstance(data, Mapping):
        return pd.Series(list(data.values()), name=name)
    if isinstance(data, np.ndarray):
        if data.ndim > 1:
            data = data.ravel()
        return pd.Series(data, name=name)
    if isinstance(data, (list, tuple, set, pd.Index, range)):
        return pd.Series(list(data), name=name)
    try:  # scalar
        return pd.Series([data], name=name)
    except Exception:  # pragma: no cover - truly exotic input
        return pd.Series(dtype=float, name=name)


def _numeric(data: Any) -> np.ndarray:
    """Return finite float values only (drops NaN/inf and non-numeric rows)."""
    series = _to_series(data)
    try:
        values = pd.to_numeric(series, errors="coerce").to_numpy(dtype=float)
    except Exception:  # pragma: no cover
        return np.asarray([], dtype=float)
    return values[np.isfinite(values)]


def _frame(data: Any) -> pd.DataFrame:
    if isinstance(data, pd.DataFrame):
        return data
    if isinstance(data, pd.Series):
        return data.to_frame()
    if data is None:
        return pd.DataFrame()
    if isinstance(data, Mapping):
        try:
            return pd.DataFrame(data)
        except Exception:
            return pd.DataFrame()
    try:
        return pd.DataFrame(data)
    except Exception:
        return pd.DataFrame()


def _pick(df: pd.DataFrame, *candidates: str) -> str | None:
    """Case-insensitive column lookup; returns the real column name."""
    if not isinstance(df, pd.DataFrame) or df.shape[1] == 0:
        return None
    lookup: dict[str, Any] = {}
    for col in df.columns:
        lookup.setdefault(str(col).strip().lower(), col)
    for cand in candidates:
        key = str(cand).strip().lower()
        if key in lookup:
            return lookup[key]
    return None


def _fmt_num(value: Any) -> str:
    try:
        v = float(value)
    except Exception:
        return str(value)
    if not math.isfinite(v):
        return "NA"
    if v == 0:
        return "0"
    av = abs(v)
    if av < 1e-3 or av >= 1e6:
        return f"{v:.2e}"
    if av >= 100:
        return f"{v:,.1f}"
    return f"{v:.3f}".rstrip("0").rstrip(".")


def _axis_stats(ax: "plt.Axes", text: str, loc: str = "upper left") -> None:
    x, ha = (0.02, "left") if loc.startswith("upper left") else (0.98, "right")
    y, va = (0.97, "top") if "upper" in loc else (0.03, "bottom")
    ax.text(
        x,
        y,
        text,
        transform=ax.transAxes,
        ha=ha,
        va=va,
        fontsize=8.5,
        bbox=dict(boxstyle="round,pad=0.35", facecolor="white", edgecolor="#c8cdd4", linewidth=0.8),
    )


def _chrom_sort_key(value: Any) -> tuple:
    """Natural ordering for chromosome labels (1..22, X, Y, MT, then others)."""
    try:
        text = str(int(float(value)))
        return (0, int(float(value)), text)
    except Exception:
        pass
    label = str(value).strip()
    special = {"X": 1, "Y": 2, "XY": 3, "M": 4, "MT": 4, "chrM": 4, "chrMT": 4}
    key = special.get(label.upper(), special.get(label, None))
    if key is not None:
        return (1, key, label.upper())
    return (2, 0, label.upper())


def _lambda_gc(pvals: np.ndarray) -> float | None:
    """Genomic inflation factor from p-values (chi-square median method)."""
    p = np.asarray(pvals, dtype=float)
    p = p[(p > 0) & (p <= 1)]
    if p.size == 0 or _scipy_stats is None:
        return None
    try:
        chi2 = _scipy_stats.chi2.isf(p, 1)
        median = float(np.nanmedian(chi2))
        lam = median / _scipy_stats.chi2.ppf(0.5, 1)
        return float(lam)
    except Exception:  # pragma: no cover
        return None


def _clean_p(pvals: Any) -> np.ndarray:
    p = _numeric(pvals)
    return p[(p >= 0) & (p <= 1)]


def _group_series(groups: Any, ids: Sequence[str]) -> pd.Series | None:
    """Normalise a group annotation into a Series indexed by sample IID."""
    n = len(ids)
    index = pd.Index([str(i) for i in ids])
    if groups is None:
        return None
    if isinstance(groups, pd.Series):
        if groups.index.equals(index):
            return groups
        try:
            aligned = groups.reindex(index)
            if aligned.notna().any():
                return aligned
        except Exception:
            pass
        if len(groups) == n:
            return pd.Series(groups.to_numpy(), index=index)
        return None
    if isinstance(groups, pd.DataFrame):
        id_col = _pick(groups, "IID", "id", "sample", "FID")
        if id_col is None and groups.shape[1] >= 2:
            id_col = groups.columns[0]
        value_cols = [c for c in groups.columns if c != id_col]
        if id_col is None or not value_cols:
            return None
        mapping = {str(k): v for k, v in zip(groups[id_col].astype(str), groups[value_cols[0]])}
        return pd.Series([mapping.get(str(i)) for i in ids], index=index)
    if isinstance(groups, Mapping):
        return pd.Series([groups.get(str(i), groups.get(i)) for i in ids], index=index)
    if isinstance(groups, (list, tuple, np.ndarray, pd.Index)):
        if len(groups) == n:
            return pd.Series(list(groups), index=index)
    return None


def _discrete_colors(n: int) -> list:
    if n <= 10:
        return [plt.get_cmap("tab10")(i) for i in range(n)]
    if n <= 20:
        return [plt.get_cmap("tab20")(i) for i in range(n)]
    base = list(plt.get_cmap("tab20").colors)
    extra = [plt.get_cmap("Set3")(i) for i in range(12)]
    pool = base + extra
    return [pool[i % len(pool)] for i in range(n)]


