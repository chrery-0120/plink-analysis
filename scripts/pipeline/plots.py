"""Plotting utilities for the ``plink-analysis`` pipeline.

Interface contract (DESIGN.md section 10)
-----------------------------------------
Every public function has the shape ``f(data, out_path, **kwargs) -> Path``
(``plot_pca_scatter`` and ``plot_kinship_heatmap`` take their extra data as a
positional argument, exactly as specified) and writes a PNG at ``DPI = 150``
through the matplotlib ``Agg`` backend.

Design rules
------------
* Labels *inside* figures are English on purpose: CJK fonts are not reliably
  available on Windows servers, and missing glyphs would silently turn into
  boxes.  Chinese explanations live in the Markdown/HTML report instead.
* The functions never raise for missing columns, empty Series or all-NaN
  input.  Instead they emit a readable placeholder figure that says why the
  plot is unavailable, so a pipeline stage can continue and the report can
  still be produced.
* Axes always get a title, axis labels and (when meaningful) a legend.
"""

