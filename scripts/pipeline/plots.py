def plot_power_curve(df: Any, out_path: Path, **kwargs) -> Path:
    """Statistical power as a function of the significance threshold α."""
    title = kwargs.get("title", "Power vs significance threshold")
    frame = _frame(df)
    alpha_col = _pick(frame, "alpha", "ALPHA", "Alpha", "threshold")
    power_col = _pick(frame, "power", "POWER", "Power")
    if alpha_col is None or power_col is None:
        return _placeholder(
            out_path,
            title,
            "required columns alpha/power not found (expected: alpha, power)",
        )
    alpha = pd.to_numeric(frame[alpha_col], errors="coerce").to_numpy(dtype=float)
    power = pd.to_numeric(frame[power_col], errors="coerce").to_numpy(dtype=float)
    keep = np.isfinite(alpha) & np.isfinite(power) & (alpha > 0)
    alpha, power = alpha[keep], power[keep]
    if alpha.size == 0:
        return _placeholder(out_path, title, "power table contains no valid rows")
    order = np.argsort(alpha)
    alpha, power = alpha[order], power[order]
    fig, ax = plt.subplots(figsize=_FIGSIZE)
    ax.plot(alpha, power, color=_C_BLUE, marker="o", markersize=5, lw=1.6, label="power")
    ax.set_xscale("log")
    ax.axhline(float(kwargs.get("target_power", 0.8)), color=_C_ORANGE, lw=1.1, ls="--", label="target = 0.8")
    ax.set_xlabel("Significance threshold alpha")
    ax.set_ylabel("Power")
    ax.set_ylim(0, 1.02)
    ax.set_title(title)
    ax.xaxis.set_major_formatter(FuncFormatter(lambda v, _pos: f"{v:g}"))
    ax.legend(loc="lower left", frameon=True)
    for a, p in zip(alpha, power):
        if alpha.size <= 8:
            ax.annotate(f"{p:.2f}", xy=(a, p), xytext=(4, 5), textcoords="offset points", fontsize=7.5, color="#333333")
    _axis_stats(ax, f"points = {alpha.size:,}", loc="upper right")
    return _savefig(fig, out_path)


def plot_effect_bias(df: Any, out_path: Path, **kwargs) -> Path:
    """Estimated vs true effect size scatter (calibration of β estimates)."""
    title = kwargs.get("title", "Effect size calibration")
    frame = _frame(df)
    true_col = _pick(frame, "true_beta", "TRUE_BETA", "beta_true", "true")
    est_col = _pick(frame, "est_beta", "EST_BETA", "beta_est", "estimated", "beta")
    if true_col is None or est_col is None:
        return _placeholder(
            out_path,
            title,
            "required columns true_beta/est_beta not found (expected: true_beta, est_beta)",
        )
    true_beta = pd.to_numeric(frame[true_col], errors="coerce").to_numpy(dtype=float)
    est_beta = pd.to_numeric(frame[est_col], errors="coerce").to_numpy(dtype=float)
    keep = np.isfinite(true_beta) & np.isfinite(est_beta)
    true_beta, est_beta = true_beta[keep], est_beta[keep]
    if true_beta.size < 2:
        return _placeholder(out_path, title, "fewer than two valid (true_beta, est_beta) pairs")
    fig, ax = plt.subplots(figsize=(6.4, 6.0))
    ax.scatter(true_beta, est_beta, s=34, color=_C_BLUE, alpha=0.8, edgecolors="white", linewidths=0.4)
    lim = max(float(np.nanmax(np.abs(true_beta))), float(np.nanmax(np.abs(est_beta))), 1e-3) * 1.08
    ax.plot([-lim, lim], [-lim, lim], color=_C_GRAY, lw=1.1, ls="--", label="y = x (no bias)")
    try:
        slope, intercept = np.polyfit(true_beta, est_beta, 1)
        corr = float(np.corrcoef(true_beta, est_beta)[0, 1])
        fitted = slope * np.array([-lim, lim]) + intercept
        ax.plot([-lim, lim], fitted, color=_C_ORANGE, lw=1.3, label="linear fit")
        _axis_stats(ax, f"slope = {slope:.3f}\nr = {corr:.3f}\nN = {true_beta.size:,}", loc="upper left")
    except Exception:  # pragma: no cover
        _axis_stats(ax, f"N = {true_beta.size:,}", loc="upper left")
    ax.set_xlim(-lim, lim)
    ax.set_ylim(-lim, lim)
    ax.set_aspect("equal", adjustable="box")
    ax.set_xlabel("True effect size (beta)")
    ax.set_ylabel("Estimated effect size (beta)")
    ax.set_title(title)
    ax.legend(loc="lower right", frameon=True)
    return _savefig(fig, out_path)


